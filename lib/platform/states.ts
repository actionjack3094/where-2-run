export type StateCode = (typeof US_STATES)[number]["code"];

export function stateByCode(code: string) {
  const normalized = code.trim().toUpperCase();
  return US_STATES.find((state) => state.code === normalized) ?? null;
}

export function stateByName(name: string) {
  const normalized = name.trim().toLowerCase().replace(/[_-]+/g, " ");
  return US_STATES.find((state) => state.name.toLowerCase() === normalized) ?? null;
}

export type ElectionLevel = "federal" | "state" | "local";

export function inferElectionLevel(officeName: string): ElectionLevel {
  const office = officeName.toLowerCase();
  if (/governor|attorney general|state senate|state house|lieutenant/.test(office)) return "state";
  if (/mayor|council|school|county|municipal|city/.test(office)) return "local";
  if (/senate|house|president|congress/.test(office)) return "federal";
  return "local";
}

export function asElectionLevel(value: string | null | undefined, officeName: string): ElectionLevel {
  if (value === "federal" || value === "state" || value === "local") return value;
  return inferElectionLevel(officeName);
}
